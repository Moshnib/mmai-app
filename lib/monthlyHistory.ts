// ============================================================
// MONTHLY history for the six scored markets, 2019 onward.
//
// Generated once from each market's own statistics office, then
// committed -- the same pattern as lib/gulfHistory.ts and
// lib/stablecoinHistory.ts. A table would add a schema and a nightly
// write for a backfill that never changes.
//
// This exists because the site's charts were showing ONE POINT PER
// YEAR while the sources publish monthly. The data was always there;
// only the stored history was annual.
//
// Sources, all already used live by this project and already licence
// audited:
//   inflation     US BLS (YoY computed from the index) - UK ONS D7G7 -
//                 EA Eurostat prc_hicp_manr - CA StatCan (YoY from the
//                 index) - AU ABS (YoY from the index)
//   unemployment  US BLS - UK ONS MGSX - EA Eurostat une_rt_m (EA21) -
//                 CA StatCan - AU ABS - JP OECD
//   policyRate    BIS WS_CBPOL monthly, all six in one call
//
// null means NOT PUBLISHED for that month, never zero. Two real gaps
// the charts must show as gaps rather than flat lines:
//
//   JAPAN INFLATION is entirely absent. OECD's price dataflow returns
//   HTTP 500 for Japan specifically (its unemployment dataflow on the
//   same host works), and Japan's own e-Stat needs a registered key.
//   Japan's monthly inflation is a known TODO, not an oversight.
//
//   AUSTRALIA INFLATION starts 2025-04. The ABS monthly CPI indicator
//   is genuinely young; a year-over-year rate needs twelve prior months
//   of index, so the series cannot start earlier. Before that Australia
//   published CPI quarterly only.
//
// UK unemployment is a rolling three-month average stamped with its
// middle month -- that is the UK's own headline measure, not a
// smoothing choice made here.
// ============================================================

